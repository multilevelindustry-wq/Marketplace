export function getCountryByCode(code) {
    const value = String(code || "").trim().toUpperCase();
    return COUNTRIES.find(c => c.iso2 === value || c.iso3 === value) || null;
}

export function populateCountrySelect(select, options = {}) {
    if (!select) return;
    const placeholder = options.placeholder || "Select country";
    const selected = String(options.selected || "").toUpperCase();

    select.innerHTML = "";
    const first = document.createElement("option");
    first.value = "";
    first.textContent = placeholder;
    select.appendChild(first);

    COUNTRIES
        .slice()
        .sort((a,b) => a.name.localeCompare(b.name))
        .forEach(country => {
            const option = document.createElement("option");
            option.value = country.iso2;
            option.textContent = country.name;
            if (country.iso2 === selected) option.selected = true;
            select.appendChild(option);
        });
}
